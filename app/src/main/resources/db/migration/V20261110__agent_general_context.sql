ALTER TABLE agent_chat_sessions
    ALTER COLUMN interview_session_id DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS context_summary TEXT,
    ADD COLUMN IF NOT EXISTS context_summary_until_sequence INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS context_summary_version INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS context_summary_updated_at TIMESTAMP(6);

ALTER TABLE agent_conversation_creation_requests
    ALTER COLUMN interview_session_id DROP NOT NULL;

CREATE TABLE IF NOT EXISTS agent_session_contexts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_session_id VARCHAR(36) NOT NULL,
    context_type VARCHAR(32) NOT NULL,
    interview_session_id VARCHAR(36),
    resource_id VARCHAR(128),
    resource_name VARCHAR(255),
    scope VARCHAR(16) NOT NULL DEFAULT 'SESSION',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    attached_at TIMESTAMP(6) NOT NULL,
    detached_at TIMESTAMP(6),
    source_message_id BIGINT,
    CONSTRAINT fk_agent_context_session
        FOREIGN KEY (agent_session_id) REFERENCES agent_chat_sessions(agent_session_id),
    CONSTRAINT uk_agent_context_reference
        UNIQUE (agent_session_id, context_type, interview_session_id, attached_at)
);

CREATE INDEX IF NOT EXISTS idx_agent_session_context_active
    ON agent_session_contexts (agent_session_id, active, attached_at DESC);

COMMENT ON TABLE agent_session_contexts IS
    'Agent 会话按需绑定的业务上下文；不复制原始面试报告内容';
COMMENT ON COLUMN agent_chat_sessions.context_summary IS
    '滚动会话摘要；原始消息仍保存在 agent_chat_messages';
COMMENT ON COLUMN agent_session_contexts.resource_id IS
    '通用上下文资源 ID；面试报告继续兼容 interview_session_id';

CREATE INDEX IF NOT EXISTS idx_agent_session_context_resource
    ON agent_session_contexts (context_type, resource_id, active);

CREATE TABLE IF NOT EXISTS agent_context_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id VARCHAR(36) NOT NULL UNIQUE,
    owner_id VARCHAR(64) NOT NULL,
    file_hash VARCHAR(64) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    content_type VARCHAR(128),
    storage_key VARCHAR(500) NOT NULL,
    storage_url VARCHAR(1000),
    extracted_text TEXT,
    preview_text TEXT,
    review_status VARCHAR(32) NOT NULL,
    security_flagged BOOLEAN NOT NULL DEFAULT FALSE,
    security_notice VARCHAR(500),
    reviewed_at TIMESTAMP(6),
    knowledge_base_id BIGINT,
    expires_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_agent_context_asset_owner_hash UNIQUE (owner_id, file_hash)
);

CREATE INDEX IF NOT EXISTS idx_agent_context_asset_owner_created
    ON agent_context_assets (owner_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_agent_context_asset_review_status
    ON agent_context_assets (review_status, expires_at);

COMMENT ON TABLE agent_context_assets IS
    'Agent 上传的私有待审核资料；审核与明确确认后才允许进入 Agent 上下文或 RAG';
COMMENT ON COLUMN agent_context_assets.extracted_text IS
    '仅用于审核和受控上下文读取；注入模型前必须经过净化、边界包裹和长度预算';
